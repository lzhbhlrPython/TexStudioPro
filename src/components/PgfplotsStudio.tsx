import { useEffect, useMemo, useRef, useState } from 'react';
import { TexArtwork } from './TexArtwork';
import {
  BarChart3,
  Check,
  Clipboard,
  Code2,
  Loader2,
  Play,
  RefreshCw,
  Sparkles,
  X,
} from 'lucide-react';
import { useI18n } from '../i18n';
import { escapeLatex } from '../lib/templates';

type PlotKind = 'line' | 'scatter' | 'bar' | 'area' | 'step';
type LegendPosition = 'north west' | 'north east' | 'south west' | 'south east' | 'outer north east';

interface ParsedData {
  headers: string[];
  rows: Array<{ label: string; values: number[] }>;
}

interface PlotOptions {
  kind: PlotKind;
  title: string;
  xLabel: string;
  yLabel: string;
  xLog: boolean;
  yLog: boolean;
  grid: boolean;
  legend: boolean;
  smooth: boolean;
  markers: boolean;
  width: number;
  height: number;
  legendPos: LegendPosition;
  extra: string;
}

const starterCsv = `run,Baseline,Optimized
1,2.4,1.9
2,3.1,2.2
3,2.8,2.5
4,4.3,3.0
5,5.0,3.5
6,4.6,3.2`;

const colors = ['blue', 'red', 'teal', 'orange', 'violet', 'brown'];

function parseCsv(text: string): ParsedData {
  const lines = text
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean);
  if (lines.length < 2) throw new Error('At least a header and one data row are required');
  const headers = lines[0].split(',').map((value) => value.trim());
  if (headers.length < 2) throw new Error('At least one data column is required');
  const rows: ParsedData['rows'] = lines.slice(1).map((line, rowIndex) => {
    const cells = line.split(',').map((value) => value.trim());
    return {
      label: cells[0] ?? String(rowIndex + 1),
      values: headers.slice(1).map((_, index) => {
        const value = Number(cells[index + 1]);
        return Number.isFinite(value) ? value : 0;
      }),
    };
  });
  return { headers, rows };
}

function axisOptions(options: PlotOptions) {
  const result = [
    `width=${options.width}cm`,
    `height=${options.height}cm`,
    `xlabel={${escapeLatex(options.xLabel || 'x')}}`,
    `ylabel={${escapeLatex(options.yLabel || 'y')}}`,
    options.title ? `title={${escapeLatex(options.title)}}` : '',
    options.xLog ? 'xmode=log' : '',
    options.yLog ? 'ymode=log' : '',
    options.grid ? 'grid=major' : '',
    options.legend ? `legend pos=${options.legendPos}` : '',
    'enlarge x limits=0.08',
    'tick label style={font=\\small}',
    'label style={font=\\small}',
    'title style={font=\\small\\bfseries}',
    'legend style={font=\\scriptsize}',
  ].filter(Boolean);
  if (options.extra.trim()) result.push(options.extra.trim());
  return result;
}

function seriesOptions(options: PlotOptions, index: number) {
  const color = colors[index % colors.length];
  const base = [`color=${color}`, 'line width=1pt'];
  if (options.kind === 'scatter') return [...base, 'only marks', 'mark=*', 'mark size=1.6pt'];
  if (options.kind === 'bar') {
    return [...base, 'ybar', 'bar width=7pt', `bar shift=${(index - 0.5) * 8}pt`, 'fill opacity=0.85'];
  }
  if (options.kind === 'area') {
    return [...base, 'fill opacity=0.16', 'draw opacity=1', 'mark=none', options.smooth ? 'smooth' : ''];
  }
  if (options.kind === 'step') return [...base, 'const plot', 'mark=*'];
  return [...base, options.markers ? 'mark=*' : 'mark=none', options.smooth ? 'smooth' : ''];
}

function generatePlots(data: ParsedData, options: PlotOptions) {
  const labels = data.rows.map((row) => row.label);
  const numericLabels = labels.every((label) => Number.isFinite(Number(label)));
  const series = data.headers.slice(1);
  const axis = axisOptions(options);
  if (!numericLabels) {
    axis.push(
      `xtick={${labels.map((_, index) => index).join(',')}}`,
      `xticklabels={${labels.map((label) => escapeLatex(label)).join(',')}}`,
    );
  }
  const plots = series.map((name, index) => {
    const coordinates = data.rows
      .map((row, rowIndex) => `(${numericLabels ? row.label : rowIndex},${row.values[index]})`)
      .join(' ');
    return `\\addplot+[${seriesOptions(options, index).filter(Boolean).join(',')}] coordinates { ${coordinates} };\n      \\addlegendentry{${escapeLatex(name)}}`;
  });
  const axisBody = `\\begin{axis}[\n      ${axis.join(',\n      ')}\n    ]\n      ${plots.join('\n      ')}\n    \\end{axis}`;
  const preview = `\\begin{tikzpicture}\n    ${axisBody}\n  \\end{tikzpicture}`;
  const figure = `% Generated by TeXPro pgfplots Studio (requires \\usepackage{pgfplots})
\\begin{figure}[htbp]
  \\centering
  \\begin{tikzpicture}
    ${axisBody}
  \\end{tikzpicture}
  \\caption{${escapeLatex(options.title || 'Chart')}}
  \\label{fig:chart}
\\end{figure}`;
  return { preview, figure };
}

interface Props {
  open: boolean;
  projectRoot: string | null;
  filePath: string | null;
  onClose: () => void;
  onInsert: (code: string) => void;
}

export function PgfplotsStudio({ open, projectRoot, filePath, onClose, onInsert }: Props) {
  const { t } = useI18n();
  const [csv, setCsv] = useState(starterCsv);
  const [options, setOptions] = useState<PlotOptions>({
    kind: 'line',
    title: 'Compile time by run',
    xLabel: 'Run',
    yLabel: 'Seconds',
    xLog: false,
    yLog: false,
    grid: true,
    legend: true,
    smooth: true,
    markers: true,
    width: 10,
    height: 6.2,
    legendPos: 'north west',
    extra: '',
  });
  const [previewPath, setPreviewPath] = useState<string | null>(null);
  const [previewError, setPreviewError] = useState<string | null>(null);
  const [log, setLog] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [copied, setCopied] = useState(false);
  const [refreshTick, setRefreshTick] = useState(0);
  const requestId = useRef(0);

  const parsedResult = useMemo(() => {
    try {
      return { data: parseCsv(csv), error: null as string | null };
    } catch (error) {
      return { data: null, error: String((error as Error).message || error) };
    }
  }, [csv]);
  const parsed = parsedResult.data;

  const generated = useMemo(
    () => (parsed ? generatePlots(parsed, options) : null),
    [parsed, options],
  );

  useEffect(() => {
    if (!open) return;
    setPreviewPath(null);
    setPreviewError(null);
    setLog(null);
    setCopied(false);
  }, [open]);

  useEffect(() => {
    if (!open || !projectRoot || !filePath || !generated) return;
    const id = ++requestId.current;
    setBusy(true);
    setPreviewError(null);
    const timer = window.setTimeout(async () => {
      try {
        const result = await window.texpro.renderTikz({
          projectRoot,
          filePath,
          source: generated.preview,
        });
        if (id !== requestId.current) return;
        if (result.ok && result.svgPath) {
          setPreviewPath(result.svgPath);
          setPreviewError(null);
          setLog(null);
        } else {
          setPreviewPath(null);
          setPreviewError(result.error || 'pgfplots rendering failed');
          setLog(result.log || null);
        }
      } catch (error) {
        if (id === requestId.current) setPreviewError(String(error));
      } finally {
        if (id === requestId.current) setBusy(false);
      }
    }, 700);
    return () => {
      window.clearTimeout(timer);
      setBusy(false);
    };
  }, [open, generated, projectRoot, filePath, refreshTick]);

  if (!open) return null;
  const previewUrl = previewPath
    ? `texpro-asset://asset/?path=${encodeURIComponent(previewPath)}`
    : null;

  const patch = (value: Partial<PlotOptions>) => setOptions((current) => ({ ...current, ...value }));

  const kinds: Array<{ id: PlotKind; label: string }> = [
    { id: 'line', label: t('Line') },
    { id: 'scatter', label: t('Scatter') },
    { id: 'bar', label: t('Bar') },
    { id: 'area', label: t('Area') },
    { id: 'step', label: t('Step') },
  ];

  return (
    <div className="modal-scrim" onMouseDown={onClose}>
      <section className="chart-studio pgf-studio" data-testid="chart-studio" onMouseDown={(event) => event.stopPropagation()}>
        <header className="studio-header">
          <div className="studio-heading">
            <div className="studio-icon"><BarChart3 size={18} /></div>
            <div>
              <span className="modal-eyebrow">{t('Chart studio')}</span>
              <h2>pgfplots Studio</h2>
            </div>
          </div>
          <div className="studio-header-actions">
            <span className={`studio-engine ${previewError ? 'failed' : previewPath ? 'ok' : ''}`}>
              {busy ? <Loader2 size={11} className="spin" /> : previewError ? null : previewPath ? <Check size={11} /> : null}
              {previewError ? t('Error') : 'pgfplots'}
            </span>
            <button className="icon-btn" onClick={onClose} title={t('Close')}><X size={16} /></button>
          </div>
        </header>

        <div className="chart-studio-body pgf-body">
          <div className="chart-data-pane">
            <div className="pane-label">
              <Clipboard size={12} /> {t('Chart data')}
              <span className="pane-hint">CSV</span>
            </div>
            <textarea
              className="chart-csv"
              value={csv}
              onChange={(event) => setCsv(event.target.value)}
              spellCheck={false}
            />
            {parsedResult.error ? (
              <div className="chart-parse-error">{t('Invalid CSV data')}: {parsedResult.error}</div>
            ) : (
              <div className="chart-data-table pgf-data-table">
                <div className="chart-data-head" style={{ gridTemplateColumns: `44px repeat(${parsed?.headers.length ? parsed.headers.length - 1 : 1}, minmax(0, 1fr))` }}>
                  <span>#</span>
                  {parsed?.headers.slice(1).map((name) => <span key={name}>{name}</span>)}
                </div>
                {parsed?.rows.map((row, index) => (
                  <div className="chart-data-row" key={`${row.label}-${index}`} style={{ gridTemplateColumns: `44px repeat(${row.values.length}, minmax(0, 1fr))` }}>
                    <span>{row.label}</span>
                    {row.values.map((value, valueIndex) => <span key={valueIndex}>{value}</span>)}
                  </div>
                ))}
              </div>
            )}
            <div className="pgf-options">
              <div className="pgf-option-title">{t('Plot options')}</div>
              <div className="pgf-kind-row">
                {kinds.map((item) => (
                  <button
                    key={item.id}
                    className={options.kind === item.id ? 'active' : ''}
                    onClick={() => patch({ kind: item.id })}
                  >
                    {item.label}
                  </button>
                ))}
              </div>
              <label><span>{t('Title')}</span><input value={options.title} onChange={(event) => patch({ title: event.target.value })} /></label>
              <div className="pgf-two">
                <label><span>{t('X axis')}</span><input value={options.xLabel} onChange={(event) => patch({ xLabel: event.target.value })} /></label>
                <label><span>{t('Y axis')}</span><input value={options.yLabel} onChange={(event) => patch({ yLabel: event.target.value })} /></label>
              </div>
              <div className="pgf-two">
                <label><span>{t('Width (cm)')}</span><input type="number" min={4} max={16} step={0.5} value={options.width} onChange={(event) => patch({ width: Number(event.target.value) })} /></label>
                <label><span>{t('Height (cm)')}</span><input type="number" min={3} max={12} step={0.5} value={options.height} onChange={(event) => patch({ height: Number(event.target.value) })} /></label>
              </div>
              <div className="pgf-check-grid">
                <label className="chart-check"><input type="checkbox" checked={options.grid} onChange={(event) => patch({ grid: event.target.checked })} /> {t('Show grid')}</label>
                <label className="chart-check"><input type="checkbox" checked={options.legend} onChange={(event) => patch({ legend: event.target.checked })} /> {t('Show legend')}</label>
                <label className="chart-check"><input type="checkbox" checked={options.smooth} onChange={(event) => patch({ smooth: event.target.checked })} /> {t('Smooth lines')}</label>
                <label className="chart-check"><input type="checkbox" checked={options.markers} onChange={(event) => patch({ markers: event.target.checked })} /> {t('Markers')}</label>
                <label className="chart-check"><input type="checkbox" checked={options.xLog} onChange={(event) => patch({ xLog: event.target.checked })} /> {t('Log X')}</label>
                <label className="chart-check"><input type="checkbox" checked={options.yLog} onChange={(event) => patch({ yLog: event.target.checked })} /> {t('Log Y')}</label>
              </div>
              <label><span>{t('Legend position')}</span>
                <select value={options.legendPos} onChange={(event) => patch({ legendPos: event.target.value as LegendPosition })}>
                  <option value="north west">north west</option>
                  <option value="north east">north east</option>
                  <option value="south west">south west</option>
                  <option value="south east">south east</option>
                  <option value="outer north east">outer north east</option>
                </select>
              </label>
              <label><span>{t('Extra axis options')}</span>
                <textarea className="pgf-extra" value={options.extra} onChange={(event) => patch({ extra: event.target.value })} placeholder="ymin=0, ymax=6, ..." />
              </label>
            </div>
          </div>

          <div className="chart-preview-pane">
            <div className="pane-label">
              <Play size={12} /> {t('Native pgfplots preview')}
              <button className="mini-refresh" onClick={() => setRefreshTick((value) => value + 1)} title={t('Refresh')}>
                <RefreshCw size={11} />
              </button>
            </div>
            <div className="chart-canvas-wrap pgf-preview">
              {busy && !previewUrl && <div className="tikz-placeholder"><Loader2 size={18} className="spin" /> {t('Typesetting diagram…')}</div>}
              {!busy && !previewUrl && !previewError && <div className="tikz-placeholder">{t('Preview will appear here.')}</div>}
              {previewUrl && <TexArtwork src={previewUrl} alt="pgfplots preview" />}
              {previewError && (
                <div className="tikz-error-box">
                  <strong>{t('Could not render this diagram')}</strong>
                  <p>{previewError}</p>
                </div>
              )}
            </div>
            {log && (
              <details className="tikz-studio-log">
                <summary>{t('Show log')}</summary>
                <pre>{log}</pre>
              </details>
            )}
            <div className="pgf-note">
              <Sparkles size={12} />
              {t('The preview is compiled by the same TeX toolchain as your document.')}
            </div>
          </div>

          <div className="chart-code-pane">
            <div className="pane-label">
              <Code2 size={12} /> {t('Generated LaTeX')}
              <span className="pane-hint">pgfplots</span>
            </div>
            <pre className="chart-code">{generated?.figure || ''}</pre>
          </div>
        </div>

        <footer className="studio-footer">
          <span className="studio-hint">{t('Data, code and the typeset preview stay in sync.')}</span>
          <div className="spacer" />
          <button className="secondary-btn" onClick={async () => {
            try {
              await navigator.clipboard.writeText(generated?.figure || '');
              setCopied(true);
              window.setTimeout(() => setCopied(false), 1400);
            } catch {
              setCopied(false);
            }
          }} disabled={!generated}>
            {copied ? <Check size={13} /> : <Clipboard size={13} />}
            {copied ? t('Copied') : t('Copy LaTeX')}
          </button>
          <button
            className="primary-btn"
            disabled={!generated || !previewPath || busy}
            onClick={() => {
              if (generated) onInsert(generated.figure);
              onClose();
            }}
          >
            <BarChart3 size={13} /> {t('Insert chart')}
          </button>
        </footer>
      </section>
    </div>
  );
}
